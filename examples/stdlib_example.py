def 示例_functools模块():
    """functools模块示例"""
    打印("=" * 50)
    打印("functools模块示例")
    打印("=" * 50)
    
    # LRU缓存
    @LRU缓存(最大容量=100)
    def 斐波那契(n):
        if n < 2:
            return n
        return 斐波那契(n-1) + 斐波那契(n-2)
    
    打印(f"斐波那契(10) = {斐波那契(10)}")
    打印(f"斐波那契(20) = {斐波那契(20)}")
    
    # 偏函数
    def 幂(底数, 指数):
        return 底数 ** 指数
    
    平方 = 偏函数(幂, 指数=2)
    立方 = 偏函数(幂, 指数=3)
    
    打印(f"平方(5) = {平方(5)}")
    打印(f"立方(3) = {立方(3)}")
    打印()


