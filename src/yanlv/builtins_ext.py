def 绝对值(数字: Union[int, float, complex]) -> Union[int, float]:
    """
    返回数字的绝对值
    
    参数:
        数字: 整数、浮点数或复数
        
    返回:
        数字的绝对值（复数返回模长）
        
    示例:
        >>> 绝对值(-5)
        5
        >>> 绝对值(-3.14)
        3.14
        >>> 绝对值(complex(3, 4))
        5.0
    """
    return abs(数字)


def 除法余数(被除数: int, 除数: int) -> tuple[int, int]:
    """
    返回商和余数的元组
    
    参数:
        被除数: 被除数
        除数: 除数
        
    返回:
        (商, 余数)元组
        
    示例:
        >>> 除法余数(10, 3)
        (3, 1)
        >>> 除法余数(-10, 3)
        (-4, 2)
    """
    return divmod(被除数, 除数)


def 最大值(
    *参数: T,
    键函数: Optional[Callable[[T], Any]] = None,
    默认值: Optional[T] = None
) -> T:
    """
    返回最大值
    
    参数:
        *参数: 可迭代对象或多个值
        键函数: 用于比较的函数
        默认值: 空序列时的默认值
        
    返回:
        最大值
        
    示例:
        >>> 最大值(1, 2, 3)
        3
        >>> 最大值([1, 2, 3])
        3
        >>> 最大值([], 默认值=0)
        0
    """
    if len(参数) == 1 and isinstance(参数[0], Iterable):
        return max(参数[0], key=键函数, default=默认值)
    return max(*参数, key=键函数)


def 最小值(
    *参数: T,
    键函数: Optional[Callable[[T], Any]] = None,
    默认值: Optional[T] = None
) -> T:
    """
    返回最小值
    
    参数:
        *参数: 可迭代对象或多个值
        键函数: 用于比较的函数
        默认值: 空序列时的默认值
        
    返回:
        最小值
        
    示例:
        >>> 最小值(1, 2, 3)
        1
        >>> 最小值([1, 2, 3])
        1
        >>> 最小值([], 默认值=0)
        0
    """
    if len(参数) == 1 and isinstance(参数[0], Iterable):
        return min(参数[0], key=键函数, default=默认值)
    return min(*参数, key=键函数)


def 幂运算(
    底数: Union[int, float],
    指数: Union[int, float],
    模数: Optional[int] = None
) -> Union[int, float]:
    """
    计算幂运算
    
    参数:
        底数: 底数
        指数: 指数
        模数: 可选的模数
        
    返回:
        底数**指数 或 (底数**指数) % 模数
        
    示例:
        >>> 幂运算(2, 10)
        1024
        >>> 幂运算(2, 10, 100)
        24
    """
    if 模数 is None:
        return pow(底数, 指数)
    return pow(底数, 指数, 模数)


def 四舍五入(数字: float, 位数: int = 0) -> Union[int, float]:
    """
    四舍五入
    
    参数:
        数字: 要舍入的数字
        位数: 保留的小数位数
        
    返回:
        舍入后的值
        
    示例:
        >>> 四舍五入(3.14159, 2)
        3.14
        >>> 四舍五入(3.5)
        4
    """
    return round(数字, 位数)


def 求和(
    可迭代对象: Iterable[Union[int, float]],
    起始值: Union[int, float] = 0
) -> Union[int, float]:
    """
    求和
    
    参数:
        可迭代对象: 要求和的序列
        起始值: 起始值
        
    返回:
        总和
        
    示例:
        >>> 求和([1, 2, 3, 4])
        10
        >>> 求和([1, 2, 3], 10)
        16
    """
    return sum(可迭代对象, 起始值)


