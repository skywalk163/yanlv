def 表达式求值(
    表达式: str,
    全局作用域: Optional[dict] = None,
    局部作用域: Optional[dict] = None
) -> Any:
    """
    求值表达式
    
    参数:
        表达式: 表达式字符串
        全局作用域: 全局命名空间
        局部作用域: 局部命名空间
        
    返回:
        表达式的值
        
    示例:
        >>> 表达式求值('1 + 2')
        3
        >>> 表达式求值('x + y', None, {'x': 1, 'y': 2})
        3
    """
    return eval(表达式, 全局作用域, 局部作用域)


def 语句执行(
    代码: str,
    全局作用域: Optional[dict] = None,
    局部作用域: Optional[dict] = None
) -> None:
    """
    执行代码语句
    
    参数:
        代码: 代码字符串
        全局作用域: 全局命名空间
        局部作用域: 局部命名空间
        
    示例:
        >>> 语句执行('x = 10')
        >>> x
        10
    """
    exec(代码, 全局作用域, 局部作用域)


def 编译代码(
    源代码: str,
    文件名: str,
    模式: str,
    标志: int = 0,
    不继承标志: int = 0,
    优化级别: int = -1
) -> Any:
    """
    编译源代码为代码对象
    
    参数:
        源代码: 源代码字符串
        文件名: 文件名（用于错误消息）
        模式: 'exec', 'eval', 'single'
        标志: 编译标志
        不继承标志: 不继承的标志
        优化级别: 优化级别
        
    返回:
        代码对象
        
    示例:
        >>> 代码 = 编译代码('print("hello")', '<string>', 'exec')
        >>> 语句执行(代码)
        hello
    """
    return compile(源代码, 文件名, 模式, 标志, 不继承标志, 优化级别)


