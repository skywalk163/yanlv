def 拉链(
    *可迭代对象: Iterable[T],
    严格模式: bool = False
) -> Iterator[tuple[T, ...]]:
    """
    并行迭代多个可迭代对象
    
    参数:
        *可迭代对象: 要并行迭代的可迭代对象
        严格模式: 是否检查长度一致（Python 3.10+）
        
    返回:
        元组的迭代器
        
    示例:
        >>> 列表(拉链([1, 2, 3], ['a', 'b', 'c']))
        [(1, 'a'), (2, 'b'), (3, 'c')]
    """
    if 严格模式 and sys.version_info >= (3, 10):
        return zip(*可迭代对象, strict=True)
    return zip(*可迭代对象)


def 映射(
    函数: Callable[[T], R],
    *可迭代对象: Iterable[T]
) -> Iterator[R]:
    """
    将函数应用到可迭代对象的每个元素
    
    参数:
        函数: 要应用的函数
        *可迭代对象: 可迭代对象
        
    返回:
        结果的迭代器
        
    示例:
        >>> 列表(映射(lambda x: x**2, [1, 2, 3]))
        [1, 4, 9]
    """
    return map(函数, *可迭代对象)


