# ============================================================================

class 有序字典(OrderedDict[K, V]):
    """
    有序字典，保持插入顺序
    
    示例:
        >>> d = 有序字典()
        >>> d['a'] = 1
        >>> d['b'] = 2
        >>> 列表(d.键())
        ['a', 'b']
    """
    
    def 移压到末尾(self, 键: K) -> None:
        """将键移动到末尾"""
        self.move_to_end(键)
    
    def 弹出最后一个(self) -> tuple[K, V]:
        """弹出最后一个元素"""
        return self.popitem()
    
    def 弹出第一个(self) -> tuple[K, V]:
        """弹出第一个元素"""
        return self.popitem(last=False)


