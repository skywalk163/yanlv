# 计数器
# ============================================================================

class 计数器(Counter):
    """
    计数器，用于计数可哈希对象
    
    参数:
        可迭代对象: 初始元素
        
    示例:
        >>> c = 计数器('hello world')
        >>> c['l']
        3
        >>> c.最常见(2)
        [('l', 3), ('o', 2)]
    """
    
    def 最常见(self, 数量: Optional[int] = None) -> list[tuple[T, int]]:
        """
        返回最常见的元素及其计数
        
        参数:
            数量: 返回的数量（None表示全部）
            
        返回:
            (元素, 计数)列表
        """
        return self.most_common(数量)
    
    def 元素(self) -> Iterable[T]:
        """
        返回所有元素的迭代器
        
        返回:
            元素迭代器
        """
        return self.elements()
    
    def 减去(self, 其他: Mapping[T, int]) -> None:
        """减去另一个计数器"""
        self.subtract(其他)
    
    def 更新计数(self, 可迭代对象: Optional[Iterable[T]] = None) -> None:
        """更新计数"""
        if 可迭代对象 is not None:
            super().update(可迭代对象)


