# 默认字典
# ============================================================================

class 默认字典(defaultdict[K, V]):
    """
    默认字典，自动创建缺失的键
    
    参数:
        默认工厂: 创建默认值的函数
        
    示例:
        >>> d = 默认字典(list)
        >>> d['a'].追加(1)
        >>> d['a']
        [1]
    """
    
    def __init__(self, 默认工厂: Optional[Callable[[], V]] = None):
        super().__init__(默认工厂)


# ============================================================================
# 链式映射
# ============================================================================

class 链式映射(ChainMap[K, V]):
    """
    链式映射，将多个字典链接在一起
    
    参数:
        *映射: 要链接的字典
        
    示例:
        >>> d1 = {'a': 1}
        >>> d2 = {'b': 2}
        >>> cm = 链式映射(d1, d2)
        >>> cm['a']
        1
        >>> cm['b']
        2
    """
    
    def 新子映射(self) -> '链式映射[K, V]':
        """创建新的子映射"""
        return self.new_child()
    
    @property
    def 父映射(self) -> '链式映射[K, V]':
        """返回父映射"""
        return self.parents


