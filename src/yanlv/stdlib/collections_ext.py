from typing import TypeVar, Callable, Any, Optional, Iterable, Mapping
from collections import (
    namedtuple, deque, Counter, OrderedDict, 
    defaultdict, ChainMap
)

T = TypeVar('T')
K = TypeVar('K')
V = TypeVar('V')


# ============================================================================
# 命名元组
# ============================================================================

def 命名元组(
    类型名称: str,
    字段名称: list[str],
    重命名: bool = False,
    默认值: Optional[tuple] = None
) -> type:
    """
    创建具有命名字段的元组子类
    
    参数:
        类型名称: 元组类型名称
        字段名称: 字段名称列表
        重命名: 是否重命名无效字段名
        默认值: 字段默认值
        
    返回:
        命名元组类
        
    示例:
        >>> 点 = 命名元组('点', ['x', 'y'])
        >>> p = 点(1, 2)
        >>> p.x
        1
        >>> p.y
        2
    """
    if 默认值 is not None:
        return namedtuple(类型名称, 字段名称, rename=重命名, defaults=默认值)
    return namedtuple(类型名称, 字段名称, rename=重命名)


