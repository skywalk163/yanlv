# 双端队列
# ============================================================================

class 双端队列(deque):
    """
    双端队列，支持在两端快速添加和删除元素
    
    参数:
        可迭代对象: 初始元素
        最大长度: 最大长度（可选）
        
    示例:
        >>> q = 双端队列([1, 2, 3])
        >>> q.左端添加(0)
        >>> q.右端添加(4)
        >>> 列表(q)
        [0, 1, 2, 3, 4]
    """
    
    def __init__(self, 可迭代对象: Optional[Iterable[T]] = None, 最大长度: Optional[int] = None):
        if 可迭代对象 is None:
            super().__init__(maxlen=最大长度)
        else:
            super().__init__(可迭代对象, maxlen=最大长度)
    
    def 左端添加(self, 元素: T) -> None:
        """在左端添加元素"""
        self.appendleft(元素)
    
    def 右端添加(self, 元素: T) -> None:
        """在右端添加元素"""
        self.append(元素)
    
    def 左端弹出(self) -> T:
        """从左端弹出元素"""
        return self.popleft()
    
    def 右端弹出(self) -> T:
        """从右端弹出元素"""
        return self.pop()
    
    def 左端扩展(self, 可迭代对象: Iterable[T]) -> None:
        """在左端扩展多个元素"""
        self.extendleft(可迭代对象)
    
    def 右端扩展(self, 可迭代对象: Iterable[T]) -> None:
        """在右端扩展多个元素"""
        self.extend(可迭代对象)
    
    def 旋转(self, 步数: int = 1) -> None:
        """旋转队列"""
        self.rotate(步数)


