"""
言律语言copy模块扩展
提供copy标准库的中文版本
"""

import copy
from typing import Any


def 浅复制(对象: Any) -> Any:
    """
    创建对象的浅复制
    
    参数:
        对象: 要复制的对象
        
    返回:
        浅复制后的对象
        
    示例:
        >>> 原列表 = [[1, 2], [3, 4]]
        >>> 新列表 = 浅复制(原列表)
        >>> 新列表[0].append(3)
        >>> 原列表[0]
        [1, 2, 3]
    """
    return copy.copy(对象)


def 深复制(对象: Any) -> Any:
    """
    创建对象的深复制
    
    参数:
        对象: 要复制的对象
        
    返回:
        深复制后的对象
        
    示例:
        >>> 原列表 = [[1, 2], [3, 4]]
        >>> 新列表 = 深复制(原列表)
        >>> 新列表[0].append(3)
        >>> 原列表[0]
        [1, 2]
    """
    return copy.deepcopy(对象)


def 复制字典(字典对象: dict, 深度: bool = False) -> dict:
    """
    复制字典
    
    参数:
        字典对象: 要复制的字典
        深度: 是否深度复制
        
    返回:
        复制后的字典
        
    示例:
        >>> 原字典 = {'数据': [1, 2, 3]}
        >>> 新字典 = 复制字典(原字典, 深度=True)
    """
    if 深度:
        return 深复制(字典对象)
    return 浅复制(字典对象)


def 复制列表(列表对象: list, 深度: bool = False) -> list:
    """
    复制列表
    
    参数:
        列表对象: 要复制的列表
        深度: 是否深度复制
        
    返回:
        复制后的列表
        
    示例:
        >>> 原列表 = [[1, 2], [3, 4]]
        >>> 新列表 = 复制列表(原列表, 深度=True)
    """
    if 深度:
        return 深复制(列表对象)
    return 浅复制(列表对象)


def 复制集合(集合对象: set) -> set:
    """
    复制集合
    
    参数:
        集合对象: 要复制的集合
        
    返回:
        复制后的集合
        
    示例:
        >>> 原集合 = {1, 2, 3}
        >>> 新集合 = 复制集合(原集合)
    """
    return 浅复制(集合对象)


def 复制对象属性(
    源对象: Any,
    目标对象: Any,
    属性列表: list = None,
    深度: bool = False
) -> None:
    """
    复制对象属性
    
    参数:
        源对象: 源对象
        目标对象: 目标对象
        属性列表: 要复制的属性列表（None表示所有属性）
        深度: 是否深度复制
        
    示例:
        >>> class 人:
        ...     def __init__(self, 姓名, 年龄):
        ...         self.姓名 = 姓名
        ...         self.年龄 = 年龄
        >>> 源 = 人('张三', 25)
        >>> 目标 = 人('', 0)
        >>> 复制对象属性(源, 目标)
    """
    if 属性列表 is None:
        属性列表 = [attr for attr in dir(源对象) if not attr.startswith('_')]
    
    for 属性名 in 属性列表:
        if hasattr(源对象, 属性名):
            值 = getattr(源对象, 属性名)
            if 深度:
                值 = 深复制(值)
            setattr(目标对象, 属性名, 值)


def 合并字典(
    目标字典: dict,
    源字典: dict,
    深度: bool = False,
    就地修改: bool = False
) -> dict:
    """
    合并两个字典
    
    参数:
        目标字典: 目标字典
        源字典: 源字典
        深度: 是否深度复制
        就地修改: 是否就地修改目标字典
        
    返回:
        合并后的字典
        
    示例:
        >>> 目标 = {'a': 1}
        >>> 源 = {'b': 2}
        >>> 合并字典(目标, 源)
        {'a': 1, 'b': 2}
    """
    if not 就地修改:
        结果 = 复制字典(目标字典, 深度=深度)
    else:
        结果 = 目标字典
    
    for 键, 值 in 源字典.items():
        if 深度:
            值 = 深复制(值)
        结果[键] = 值
    
    return 结果


def 克隆对象(对象: Any, 深度: bool = True) -> Any:
    """
    克隆对象（默认深度复制）
    
    参数:
        对象: 要克隆的对象
        深度: 是否深度克隆
        
    返回:
        克隆后的对象
        
    示例:
        >>> 原对象 = {'数据': [1, 2, 3]}
        >>> 新对象 = 克隆对象(原对象)
    """
    if 深度:
        return 深复制(对象)
    return 浅复制(对象)


def 是否为可变对象(对象: Any) -> bool:
    """
    检查对象是否为可变对象
    
    参数:
        对象: 要检查的对象
        
    返回:
        是否为可变对象
        
    示例:
        >>> 是否为可变对象([1, 2, 3])
        True
        >>> 是否为可变对象((1, 2, 3))
        False
    """
    可变类型 = (list, dict, set, bytearray)
    return isinstance(对象, 可变类型)


def 是否需要深复制(对象: Any) -> bool:
    """
    检查对象是否需要深复制
    
    参数:
        对象: 要检查的对象
        
    返回:
        是否需要深复制
        
    示例:
        >>> 是否需要深复制([[1, 2], [3, 4]])
        True
        >>> 是否需要深复制([1, 2, 3])
        False
    """
    if isinstance(对象, (list, tuple)):
        return any(是否为可变对象(元素) for 元素 in 对象)
    elif isinstance(对象, dict):
        return any(是否为可变对象(值) for 值 in 对象.values())
    return False


