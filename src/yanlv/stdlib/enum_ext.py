"""
言律语言enum模块扩展
提供enum标准库的中文版本
"""

from enum import Enum, IntEnum, Flag, IntFlag, auto
from typing import Any, Type, List


class 枚举基类(Enum):
    """
    枚举基类
    
    示例:
        >>> class 颜色(枚举基类):
        ...     红色 = 1
        ...     绿色 = 2
        ...     蓝色 = 3
        >>> 颜色.红色.value
        1
    """
    pass


class 整数枚举(IntEnum):
    """
    整数枚举基类
    
    示例:
        >>> class 状态(整数枚举):
        ...     待处理 = 1
        ...     处理中 = 2
        ...     已完成 = 3
    """
    pass


class 标志基类(Flag):
    """
    标志基类（支持位运算）
    
    示例:
        >>> class 权限(标志基类):
        ...     读取 = 1
        ...     写入 = 2
        ...     执行 = 4
    """
    pass


class 整数标志(IntFlag):
    """
    整数标志基类（支持位运算）
    
    示例:
        >>> class 文件权限(整数标志):
        ...     读取 = 4
        ...     写入 = 2
        ...     执行 = 1
    """
    pass


def 自动值() -> auto:
    """
    自动生成枚举值
    
    返回:
        auto对象
        
    示例:
        >>> class 颜色(枚举基类):
        ...     红色 = 自动值()
        ...     绿色 = 自动值()
        ...     蓝色 = 自动值()
    """
    return auto()


def 创建枚举(
    类名: str,
    名称值字典: dict,
    基类: Type = Enum
) -> Type:
    """
    动态创建枚举类
    
    参数:
        类名: 枚举类名称
        名称值字典: 枚举名称和值的字典
        基类: 枚举基类
        
    返回:
        枚举类
        
    示例:
        >>> 颜色 = 创建枚举('颜色', {'红色': 1, '绿色': 2, '蓝色': 3})
        >>> 颜色.红色.value
        1
    """
    return 基类(类名, 名称值字典)


def 从值获取枚举(枚举类: Type, 值: Any) -> Any:
    """
    从值获取枚举成员
    
    参数:
        枚举类: 枚举类
        值: 枚举值
        
    返回:
        枚举成员
        
    示例:
        >>> class 颜色(枚举基类):
        ...     红色 = 1
        ...     绿色 = 2
        >>> 从值获取枚举(颜色, 1)
        <颜色.红色: 1>
    """
    return 枚举类(值)


def 从名称获取枚举(枚举类: Type, 名称: str) -> Any:
    """
    从名称获取枚举成员
    
    参数:
        枚举类: 枚举类
        名称: 枚举名称
        
    返回:
        枚举成员
        
    示例:
        >>> class 颜色(枚举基类):
        ...     红色 = 1
        ...     绿色 = 2
        >>> 从名称获取枚举(颜色, '红色')
        <颜色.红色: 1>
    """
    return 枚举类[名称]


def 获取所有枚举成员(枚举类: Type) -> List:
    """
    获取枚举类的所有成员
    
    参数:
        枚举类: 枚举类
        
    返回:
        枚举成员列表
        
    示例:
        >>> class 颜色(枚举基类):
        ...     红色 = 1
        ...     绿色 = 2
        >>> 获取所有枚举成员(颜色)
        [<颜色.红色: 1>, <颜色.绿色: 2>]
    """
    return list(枚举类)


def 获取所有枚举名称(枚举类: Type) -> List[str]:
    """
    获取枚举类的所有成员名称
    
    参数:
        枚举类: 枚举类
        
    返回:
        名称列表
        
    示例:
        >>> class 颜色(枚举基类):
        ...     红色 = 1
        ...     绿色 = 2
        >>> 获取所有枚举名称(颜色)
        ['红色', '绿色']
    """
    return [成员.name for 成员 in 枚举类]


def 获取所有枚举值(枚举类: Type) -> List:
    """
    获取枚举类的所有成员值
    
    参数:
        枚举类: 枚举类
        
    返回:
        值列表
        
    示例:
        >>> class 颜色(枚举基类):
        ...     红色 = 1
        ...     绿色 = 2
        >>> 获取所有枚举值(颜色)
        [1, 2]
    """
    return [成员.value for 成员 in 枚举类]


def 枚举成员数(枚举类: Type) -> int:
    """
    获取枚举类的成员数量
    
    参数:
        枚举类: 枚举类
        
    返回:
        成员数量
        
    示例:
        >>> class 颜色(枚举基类):
        ...     红色 = 1
        ...     绿色 = 2
        ...     蓝色 = 3
        >>> 枚举成员数(颜色)
        3
    """
    return len(list(枚举类))


def 是否为枚举成员(枚举类: Type, 值: Any) -> bool:
    """
    检查值是否为枚举成员
    
    参数:
        枚举类: 枚举类
        值: 要检查的值
        
    返回:
        是否为枚举成员
        
    示例:
        >>> class 颜色(枚举基类):
        ...     红色 = 1
        ...     绿色 = 2
        >>> 是否为枚举成员(颜色, 1)
        True
        >>> 是否为枚举成员(颜色, 3)
        False
    """
    try:
        枚举类(值)
        return True
    except ValueError:
        return False


def 枚举转字典(枚举类: Type) -> dict:
    """
    将枚举类转换为字典
    
    参数:
        枚举类: 枚举类
        
    返回:
        名称到值的字典
        
    示例:
        >>> class 颜色(枚举基类):
        ...     红色 = 1
        ...     绿色 = 2
        >>> 枚举转字典(颜色)
        {'红色': 1, '绿色': 2}
    """
    return {成员.name: 成员.value for 成员 in 枚举类}


def 合并枚举(类名: str, *枚举类列表: Type) -> Type:
    """
    合并多个枚举类
    
    参数:
        类名: 新枚举类名称
        *枚举类列表: 要合并的枚举类
        
    返回:
        合并后的枚举类
        
    示例:
        >>> class 颜色1(枚举基类):
        ...     红色 = 1
        >>> class 颜色2(枚举基类):
        ...     蓝色 = 2
        >>> 合并颜色 = 合并枚举('合并颜色', 颜色1, 颜色2)
    """
    合并字典 = {}
    for 枚举类 in 枚举类列表:
        合并字典.update(枚举转字典(枚举类))
    return 创建枚举(类名, 合并字典)


