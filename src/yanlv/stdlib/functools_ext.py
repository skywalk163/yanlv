from typing import TypeVar, Callable, Any, Optional, Iterable
from functools import (
    lru_cache, cache, cached_property,
    partial, partialmethod,
    reduce, wraps, update_wrapper
)

T = TypeVar('T')
R = TypeVar('R')


# ============================================================================
# 缓存装饰器
# ============================================================================

def LRU缓存(
    最大容量: int = 128,
    类型化: bool = False
) -> Callable[[Callable], Callable]:
    """
    LRU缓存装饰器
    
    参数:
        最大容量: 最大缓存容量
        类型化: 是否区分参数类型
        
    返回:
        装饰器
        
    示例:
        >>> @LRU缓存(最大容量=100)
        ... def 斐波那契(n):
        ...     if n < 2:
        ...         return n
        ...     return 斐波那契(n-1) + 斐波那契(n-2)
        >>> 斐波那契(100)
        354224848179261915075
    """
    return lru_cache(maxsize=最大容量, typed=类型化)


def 无限缓存() -> Callable[[Callable], Callable]:
    """
    无限缓存装饰器
    
    返回:
        装饰器
        
    示例:
        >>> @无限缓存()
        ... def 阶乘(n):
        ...     return n * 阶乘(n-1) if n else 1
        >>> 阶乘(10)
        3628800
    """
    return cache()


def 缓存属性(函数: Callable) -> Any:
    """
    缓存属性装饰器
    
    参数:
        函数: getter函数
        
    返回:
        cached_property对象
        
    示例:
        >>> class 圆:
        ...     def __init__(self, 半径):
        ...         self.半径 = 半径
        ...     @缓存属性
        ...     def 面积(self):
        ...         打印('计算面积')
        ...         return 3.14159 * self.半径 ** 2
        >>> c = 圆(5)
        >>> c.面积  # 第一次计算
        计算面积
        78.53975
        >>> c.面积  # 使用缓存
        78.53975
    """
    return cached_property(函数)


