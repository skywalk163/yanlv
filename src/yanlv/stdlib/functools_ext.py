def 包装器(
    包装函数: Callable,
    被包装函数: Optional[Callable] = None,
    更新元组: tuple = (),
    忽略属性: set = frozenset()
) -> Callable:
    """
    包装器装饰器
    
    参数:
        包装函数: 包装函数
        被包装函数: 被包装函数
        更新元组: 要更新的属性
        忽略属性: 要忽略的属性
        
    返回:
        装饰器或包装后的函数
        
    示例:
        >>> def 装饰器(函数):
        ...     @包装器(函数)
        ...     def 包装(*args, **kwargs):
        ...         打印('调用前')
        ...         结果 = 函数(*args, **kwargs)
        ...         打印('调用后')
        ...         return 结果
        ...     return 包装
        >>> @装饰器
        ... def 问候(名字):
        ...     return f'你好, {名字}'
        >>> 问候('张三')
        调用前
        调用后
        '你好, 张三'
    """
    if 被包装函数 is None:
        return wraps(包装函数, updated=更新元组, assigned=更新元组)
    return wraps(被包装函数, updated=更新元组, assigned=更新元组)(包装函数)


def 更新包装器(
    包装函数: Callable,
    被包装函数: Callable,
    更新元组: tuple = (),
    忽略属性: set = frozenset()
) -> Callable:
    """
    更新包装器
    
    参数:
        包装函数: 包装函数
        被包装函数: 被包装函数
        更新元组: 要更新的属性
        忽略属性: 要忽略的属性
        
    返回:
        更新后的包装函数
        
    示例:
        >>> def 原函数():
        ...     '''原函数文档'''
        ...     pass
        >>> def 包装函数():
        ...     pass
        >>> 更新包装器(包装函数, 原函数)
        >>> 包装函数.__doc__
        '原函数文档'
    """
    return update_wrapper(包装函数, 被包装函数, updated=更新元组, assigned=更新元组)


