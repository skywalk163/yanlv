# ============================================================================

def 偏函数(
    函数: Callable,
    *参数: Any,
    **关键字参数: Any
) -> Callable:
    """
    创建偏函数
    
    参数:
        函数: 原函数
        *参数: 固定的位置参数
        **关键字参数: 固定的关键字参数
        
    返回:
        偏函数
        
    示例:
        >>> def 幂(底数, 指数):
        ...     return 底数 ** 指数
        >>> 平方 = 偏函数(幂, 指数=2)
        >>> 平方(3)
        9
        >>> 立方 = 偏函数(幂, 指数=3)
        >>> 立方(3)
        27
    """
    return partial(函数, *参数, **关键字参数)


def 偏方法(
    函数: Callable,
    *参数: Any,
    **关键字参数: Any
) -> Any:
    """
    创建偏方法
    
    参数:
        函数: 原函数
        *参数: 固定的位置参数
        **关键字参数: 固定的关键字参数
        
    返回:
        partialmethod对象
        
    示例:
        >>> class 示例:
        ...     def 方法(self, x, y):
        ...         return x + y
        ...     偏调 = 偏方法(方法, 10)
        >>> obj = 示例()
        >>> obj.偏调(5)
        15
    """
    return partialmethod(函数, *参数, **关键字参数)


# ============================================================================
# 归约函数
# ============================================================================

def 归约(
    函数: Callable[[T, T], T],
    可迭代对象: Iterable[T],
    初始值: Optional[T] = None
) -> T:
    """
    归约函数
    
    参数:
        函数: 归约函数
        可迭代对象: 可迭代对象
        初始值: 初始值
        
    返回:
        归约结果
        
    示例:
        >>> 归约(lambda x, y: x + y, [1, 2, 3, 4])
        10
        >>> 归约(lambda x, y: x * y, [1, 2, 3, 4])
        24
    """
    if 初始值 is not None:
        return reduce(函数, 可迭代对象, 初始值)
    return reduce(函数, 可迭代对象)


