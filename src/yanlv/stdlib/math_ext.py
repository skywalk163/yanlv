def 符号函数(数字: Union[int, float]) -> float:
    """
    符号函数
    
    参数:
        数字: 数字
        
    返回:
        -1, 0, 或 1
        
    示例:
        >>> 符号函数(-5)
        -1.0
        >>> 符号函数(0)
        0.0
        >>> 符号函数(5)
        1.0
    """
    return math.copysign(1, 数字)


def 是否有限(数字: Union[int, float]) -> bool:
    """检查是否为有限数"""
    return math.isfinite(数字)


def 是否无穷(数字: Union[int, float]) -> bool:
    """检查是否为无穷大"""
    return math.isinf(数字)


def 是否非数(数字: Union[int, float]) -> bool:
    """检查是否为NaN"""
    return math.isnan(数字)


def 是否接近(
    a: Union[int, float],
    b: Union[int, float],
    相对容差: float = 1e-9,
    绝对容差: float = 0.0
) -> bool:
    """
    检查两个数是否接近
    
    参数:
        a: 第一个数
        b: 第二个数
        相对容差: 相对容差
        绝对容差: 绝对容差
        
    返回:
        是否接近
        
    示例:
        >>> 是否接近(0.1 + 0.2, 0.3)
        True
    """
    return math.isclose(a, b, rel_tol=相对容差, abs_tol=绝对容差)


