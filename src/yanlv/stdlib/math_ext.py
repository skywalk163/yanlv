import math
from typing import Union


# ============================================================================
# 基本数学函数
# ============================================================================

def 平方根(数字: Union[int, float]) -> float:
    """
    计算平方根
    
    参数:
        数字: 非负数
        
    返回:
        平方根
        
    示例:
        >>> 平方根(16)
        4.0
    """
    return math.sqrt(数字)


def 立方根(数字: Union[int, float]) -> float:
    """
    计算立方根
    
    参数:
        数字: 数字
        
    返回:
        立方根
        
    示例:
        >>> 立方根(27)
        3.0
    """
    return 数字 ** (1/3)


def 幂函数(底数: Union[int, float], 指数: Union[int, float]) -> float:
    """
    计算幂
    
    参数:
        底数: 底数
        指数: 指数
        
    返回:
        底数的指数次幂
        
    示例:
        >>> 幂函数(2, 10)
        1024.0
    """
    return math.pow(底数, 指数)


def 指数函数(数字: Union[int, float]) -> float:
    """
    计算e的幂
    
    参数:
        数字: 指数
        
    返回:
        e的数字次幂
        
    示例:
        >>> 指数函数(1)
        2.718281828459045
    """
    return math.exp(数字)


def 自然对数(数字: Union[int, float]) -> float:
    """
    计算自然对数（以e为底）
    
    参数:
        数字: 正数
        
    返回:
        自然对数
        
    示例:
        >>> 自然对数(2.718281828459045)
        1.0
    """
    return math.log(数字)


def 对数(数字: Union[int, float], 底数: Union[int, float] = 10) -> float:
    """
    计算对数
    
    参数:
        数字: 正数
        底数: 对数的底（默认为10）
        
    返回:
        对数
        
    示例:
        >>> 对数(100, 10)
        2.0
        >>> 对数(8, 2)
        3.0
    """
    return math.log(数字, 底数)


def 二进制对数(数字: Union[int, float]) -> float:
    """
    计算以2为底的对数
    
    参数:
        数字: 正数
        
    返回:
        二进制对数
        
    示例:
        >>> 二进制对数(8)
        3.0
    """
    return math.log2(数字)


def 常用对数(数字: Union[int, float]) -> float:
    """
    计算以10为底的对数
    
    参数:
        数字: 正数
        
    返回:
        常用对数
        
    示例:
        >>> 常用对数(100)
        2.0
    """
    return math.log10(数字)


# ============================================================================
# 三角函数
# ============================================================================

def 正弦(弧度: Union[int, float]) -> float:
    """
    计算正弦值
    
    参数:
        弧度: 弧度值
        
    返回:
        正弦值
        
    示例:
        >>> 正弦(3.14159 / 2)
        1.0
    """
    return math.sin(弧度)


def 余弦(弧度: Union[int, float]) -> float:
    """
    计算余弦值
    
    参数:
        弧度: 弧度值
        
    返回:
        余弦值
        
    示例:
        >>> 余弦(0)
        1.0
    """
    return math.cos(弧度)


def 正切(弧度: Union[int, float]) -> float:
    """
    计算正切值
    
    参数:
        弧度: 弧度值
        
    返回:
        正切值
        
    示例:
        >>> 正切(3.14159 / 4)
        1.0
    """
    return math.tan(弧度)


def 反正弦(值: Union[int, float]) -> float:
    """
    计算反正弦值
    
    参数:
        值: -1到1之间的值
        
    返回:
        弧度值
        
    示例:
        >>> 反正弦(1)
        1.5707963267948966
    """
    return math.asin(值)


def 反余弦(值: Union[int, float]) -> float:
    """
    计算反余弦值
    
    参数:
        值: -1到1之间的值
        
    返回:
        弧度值
        
    示例:
        >>> 反余弦(0)
        1.5707963267948966
    """
    return math.acos(值)


def 反正切(值: Union[int, float]) -> float:
    """
    计算反正切值
    
    参数:
        值: 任意值
        
    返回:
        弧度值
        
    示例:
        >>> 反正切(1)
        0.7853981633974483
    """
    return math.atan(值)


def 双参数反正切(y: Union[int, float], x: Union[int, float]) -> float:
    """
    计算双参数反正切值
    
    参数:
        y: y坐标
        x: x坐标
        
    返回:
        弧度值
        
    示例:
        >>> 双参数反正切(1, 1)
        0.7853981633974483
    """
    return math.atan2(y, x)


# ============================================================================
# 双曲函数
