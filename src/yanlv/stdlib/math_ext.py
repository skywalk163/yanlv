def 阶乘(整数: int) -> int:
    """
    计算阶乘
    
    参数:
        整数: 非负整数
        
    返回:
        阶乘值
        
    示例:
        >>> 阶乘(5)
        120
    """
    return math.factorial(整数)


def 组合数(n: int, k: int) -> int:
    """
    计算组合数 C(n, k)
    
    参数:
        n: 总数
        k: 选取数
        
    返回:
        组合数
        
    示例:
        >>> 组合数(5, 2)
        10
    """
    return math.comb(n, k)


def 排列数(n: int, k: int) -> int:
    """
    计算排列数 P(n, k)
    
    参数:
        n: 总数
        k: 选取数
        
    返回:
        排列数
        
    示例:
        >>> 排列数(5, 2)
        20
    """
    return math.perm(n, k)


def 伽玛函数(值: Union[int, float]) -> float:
    """
    计算伽玛函数
    
    参数:
        值: 正数
        
    返回:
        伽玛函数值
        
    示例:
        >>> 伽玛函数(5)
        24.0
    """
    return math.gamma(值)


def 对数伽玛函数(值: Union[int, float]) -> float:
    """计算伽玛函数的自然对数"""
    return math.lgamma(值)


# ============================================================================
# 数值处理
# ============================================================================

def 向下取整(数字: Union[int, float]) -> int:
    """
    向下取整
    
    参数:
        数字: 数字
        
    返回:
        不大于数字的最大整数
        
    示例:
        >>> 向下取整(3.7)
        3
        >>> 向下取整(-3.7)
        -4
    """
    return math.floor(数字)


def 向上取整(数字: Union[int, float]) -> int:
    """
    向上取整
    
    参数:
        数字: 数字
        
    返回:
        不小于数字的最小整数
        
    示例:
        >>> 向上取整(3.3)
        4
        >>> 向上取整(-3.3)
        -3
    """
    return math.ceil(数字)


def 截断(数字: Union[int, float]) -> int:
    """
    截断小数部分
    
    参数:
        数字: 数字
        
    返回:
        整数部分
        
    示例:
        >>> 截断(3.7)
        3
        >>> 截断(-3.7)
        -3
    """
    return math.trunc(数字)


def 绝对值(数字: Union[int, float]) -> float:
    """计算绝对值"""
    return math.fabs(数字)


def 模运算(x: Union[int, float], y: Union[int, float]) -> float:
    """
    计算模运算结果
    
    参数:
        x: 被除数
        y: 除数
        
    返回:
        x % y
        
    示例:
        >>> 模运算(10, 3)
        1.0
    """
    return math.fmod(x, y)


def 余数函数(x: Union[int, float], y: Union[int, float]) -> float:
    """计算IEEE 754余数"""
    return math.remainder(x, y)


# ============================================================================
# 符号和比较
