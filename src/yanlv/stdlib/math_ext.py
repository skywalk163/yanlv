def 双曲正弦(值: Union[int, float]) -> float:
    """计算双曲正弦值"""
    return math.sinh(值)


def 双曲余弦(值: Union[int, float]) -> float:
    """计算双曲余弦值"""
    return math.cosh(值)


def 双曲正切(值: Union[int, float]) -> float:
    """计算双曲正切值"""
    return math.tanh(值)


# ============================================================================
# 角度转换
# ============================================================================

def 弧度转角度(弧度: Union[int, float]) -> float:
    """
    弧度转角度
    
    参数:
        弧度: 弧度值
        
    返回:
        角度值
        
    示例:
        >>> 弧度转角度(3.14159)
        180.0
    """
    return math.degrees(弧度)


def 角度转弧度(角度: Union[int, float]) -> float:
    """
    角度转弧度
    
    参数:
        角度: 角度值
        
    返回:
        弧度值
        
    示例:
        >>> 角度转弧度(180)
        3.141592653589793
    """
    return math.radians(角度)


