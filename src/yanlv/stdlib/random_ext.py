import random
from typing import Sequence, TypeVar, Optional, List

T = TypeVar('T')


# ============================================================================
# 基本随机函数
# ============================================================================

def 随机整数(最小值: int, 最大值: int) -> int:
    """
    生成随机整数
    
    参数:
        最小值: 最小值（包含）
        最大值: 最大值（包含）
        
    返回:
        随机整数
        
    示例:
        >>> 随机整数(1, 100)
        42
    """
    return random.randint(最小值, 最大值)


def 随机浮点数(最小值: float = 0.0, 最大值: float = 1.0) -> float:
    """
    生成随机浮点数
    
    参数:
        最小值: 最小值（包含）
        最大值: 最大值（不包含）
        
    返回:
        随机浮点数
        
    示例:
        >>> 随机浮点数(0, 10)
        3.14159...
    """
    return random.uniform(最小值, 最大值)


def 随机选择(序列: Sequence[T]) -> T:
    """
    从序列中随机选择一个元素
    
    参数:
        序列: 序列
        
    返回:
        随机选择的元素
        
    示例:
        >>> 随机选择(['苹果', '香蕉', '橙子'])
        '香蕉'
    """
    return random.choice(序列)


def 随机选择多个(序列: Sequence[T], 数量: int) -> List[T]:
    """
    从序列中随机选择多个元素（可重复）
    
    参数:
        序列: 序列
        数量: 选择数量
        
    返回:
        随机选择的元素列表
        
    示例:
        >>> 随机选择多个(['红', '绿', '蓝'], 5)
        ['红', '蓝', '红', '绿', '蓝']
    """
    return random.choices(序列, k=数量)


def 随机采样(序列: Sequence[T], 数量: int) -> List[T]:
    """
    从序列中随机采样（不重复）
    
    参数:
        序列: 序列
        数量: 采样数量
        
    返回:
        随机采样的元素列表
        
    示例:
        >>> 随机采样([1, 2, 3, 4, 5], 3)
        [2, 5, 1]
    """
    return random.sample(序列, 数量)


def 随机打乱(序列: List[T]) -> None:
    """
    随机打乱序列（原地修改）
    
    参数:
        序列: 要打乱的序列
        
    示例:
        >>> 列表 = [1, 2, 3, 4, 5]
        >>> 随机打乱(列表)
        >>> 列表
        [3, 1, 5, 2, 4]
    """
    random.shuffle(序列)


def 随机范围(起始: int, 结束: int, 步长: int = 1) -> int:
    """
    从范围内随机选择一个整数
    
    参数:
        起始: 起始值
        结束: 结束值
        步长: 步长
        
    返回:
        随机整数
        
    示例:
        >>> 随机范围(0, 100, 5)
        35
    """
    return random.randrange(起始, 结束, 步长)


# ============================================================================
# 分布函数
# ============================================================================

def 正态分布随机数(均值: float = 0.0, 标准差: float = 1.0) -> float:
    """
    生成正态分布随机数
    
    参数:
        均值: 均值
        标准差: 标准差
        
    返回:
        随机数
        
    示例:
        >>> 正态分布随机数(100, 15)
        98.5...
    """
    return random.gauss(均值, 标准差)


def 指数分布随机数(参数: float = 1.0) -> float:
    """
    生成指数分布随机数
    
    参数:
        参数: λ参数
        
    返回:
        随机数
        
    示例:
        >>> 指数分布随机数(0.5)
        1.23...
    """
    return random.expovariate(参数)


def 均匀分布随机数(最小值: float, 最大值: float) -> float:
    """
    生成均匀分布随机数
    
    参数:
        最小值: 最小值
        最大值: 最大值
        
    返回:
        随机数
        
    示例:
        >>> 均匀分布随机数(0, 100)
        42.5...
    """
    return random.uniform(最小值, 最大值)


def 对数正态分布随机数(均值: float, 标准差: float) -> float:
    """
    生成对数正态分布随机数
    
    参数:
        均值: 均值
        标准差: 标准差
        
    返回:
        随机数
    """
    return random.lognormvariate(均值, 标准差)


def 三角分布随机数(最小值: float, 众数: float, 最大值: float) -> float:
    """
    生成三角分布随机数
    
    参数:
        最小值: 最小值
        众数: 众数
        最大值: 最大值
        
    返回:
        随机数
    """
    return random.triangular(最小值, 最大值, 众数)


def 贝塔分布随机数(参数a: float, 参数b: float) -> float:
    """
    生成贝塔分布随机数
    
    参数:
        参数a: α参数
        参数b: β参数
        
    返回:
        随机数
    """
    return random.betavariate(参数a, 参数b)


def 伽玛分布随机数(形状: float, 尺度: float) -> float:
    """
    生成伽玛分布随机数
    
    参数:
        形状: 形状参数
        尺度: 尺度参数
        
    返回:
        随机数
    """
    return random.gammavariate(形状, 尺度)


# ============================================================================
# 随机种子和状态
# ============================================================================

def 设置随机种子(种子: Optional[int] = None) -> None:
    """
    设置随机种子
    
    参数:
        种子: 种子值（None表示使用系统时间）
        
    示例:
        >>> 设置随机种子(42)
        >>> 随机整数(1, 100)
        82
        >>> 设置随机种子(42)
        >>> 随机整数(1, 100)
        82
    """
    random.seed(种子)


def 获取随机状态() -> object:
    """
    获取当前随机状态
    
    返回:
        随机状态对象
        
    示例:
        >>> 状态 = 获取随机状态()
        >>> 随机整数(1, 100)
        42
        >>> 设置随机状态(状态)
        >>> 随机整数(1, 100)
        42
    """
    return random.getstate()


def 设置随机状态(状态: object) -> None:
    """
    设置随机状态
    
    参数:
        状态: 随机状态对象
    """
    random.setstate(状态)


