# 分布形状度量
# ============================================================================

def 偏度(数据: Iterable[Union[int, float]]) -> float:
    """
    计算偏度（衡量分布的不对称程度）
    
    参数:
        数据: 数值数据
        
    返回:
        偏度值
        
    示例:
        >>> 偏度([1, 2, 2, 3, 4])
        0.0
    """
    数据列表 = list(数据)
    n = len(数据列表)
    均值 = 平均值(数据列表)
    标准差值 = 标准差(数据列表)
    
    if 标准差值 == 0:
        return 0
    
    偏度和 = sum((x - 均值) ** 3 for x in 数据列表)
    return 偏度和 / (n * 标准差值 ** 3)


def 峰度(数据: Iterable[Union[int, float]]) -> float:
    """
    计算峰度（衡量分布的尖锐程度）
    
    参数:
        数据: 数值数据
        
    返回:
        峰度值
        
    示例:
        >>> 峰度([1, 2, 3, 4, 5])
        -1.3
    """
    数据列表 = list(数据)
    n = len(数据列表)
    均值 = 平均值(数据列表)
    标准差值 = 标准差(数据列表)
    
    if 标准差值 == 0:
        return 0
    
    峰度和 = sum((x - 均值) ** 4 for x in 数据列表)
    return 峰度和 / (n * 标准差值 ** 4) - 3


