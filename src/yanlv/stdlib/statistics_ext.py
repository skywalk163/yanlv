def 变异系数(数据: Iterable[Union[int, float]]) -> float:
    """
    计算变异系数（标准差/平均值）
    
    参数:
        数据: 数值数据
        
    返回:
        变异系数
        
    示例:
        >>> 变异系数([1, 2, 3, 4, 5])
        0.5270462766947299
    """
    数据列表 = list(数据)
    均值 = 平均值(数据列表)
    if 均值 == 0:
        return 0
    return 标准差(数据列表) / abs(均值)


def 协方差(
    数据x: Iterable[Union[int, float]],
    数据y: Iterable[Union[int, float]],
    总体协方差: bool = False
) -> float:
    """
    计算协方差
    
    参数:
        数据x: 第一组数据
        数据y: 第二组数据
        总体协方差: 是否计算总体协方差
        
    返回:
        协方差
        
    示例:
        >>> 协方差([1, 2, 3], [4, 5, 6])
        1.0
    """
    x列表 = list(数据x)
    y列表 = list(数据y)
    
    if len(x列表) != len(y列表):
        raise ValueError("两组数据的长度必须相同")
    
    n = len(x列表)
    均值x = 平均值(x列表)
    均值y = 平均值(y列表)
    
    协方差和 = sum((x - 均值x) * (y - 均值y) for x, y in zip(x列表, y列表))
    
    if 总体协方差:
        return 协方差和 / n
    return 协方差和 / (n - 1)


def 相关系数(
    数据x: Iterable[Union[int, float]],
    数据y: Iterable[Union[int, float]]
) -> float:
    """
    计算皮尔逊相关系数
    
    参数:
        数据x: 第一组数据
        数据y: 第二组数据
        
    返回:
        相关系数（-1到1之间）
        
    示例:
        >>> 相关系数([1, 2, 3], [4, 5, 6])
        1.0
    """
    x列表 = list(数据x)
    y列表 = list(数据y)
    
    if len(x列表) != len(y列表):
        raise ValueError("两组数据的长度必须相同")
    
    协方差值 = 协方差(x列表, y列表)
    标准差x = 标准差(x列表)
    标准差y = 标准差(y列表)
    
    if 标准差x == 0 or 标准差y == 0:
        return 0
    
    return 协方差值 / (标准差x * 标准差y)


def 线性回归(
    数据x: Iterable[Union[int, float]],
    数据y: Iterable[Union[int, float]]
) -> tuple[float, float]:
    """
    计算线性回归参数
    
    参数:
        数据x: 自变量数据
        数据y: 因变量数据
        
    返回:
        (斜率, 截距)
        
    示例:
        >>> 线性回归([1, 2, 3], [2, 4, 6])
        (2.0, 0.0)
    """
    x列表 = list(数据x)
    y列表 = list(数据y)
    
    if len(x列表) != len(y列表):
        raise ValueError("两组数据的长度必须相同")
    
    n = len(x列表)
    均值x = 平均值(x列表)
    均值y = 平均值(y列表)
    
    分子 = sum((x - 均值x) * (y - 均值y) for x, y in zip(x列表, y列表))
    分母 = sum((x - 均值x) ** 2 for x in x列表)
    
    if 分母 == 0:
        return (0, 均值y)
    
    斜率 = 分子 / 分母
    截距 = 均值y - 斜率 * 均值x
    
    return (斜率, 截距)


