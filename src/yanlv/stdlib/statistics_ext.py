import statistics
from typing import List, Union, Optional
from collections.abc import Iterable


# ============================================================================
# 集中趋势度量
# ============================================================================

def 平均值(数据: Iterable[Union[int, float]]) -> float:
    """
    计算算术平均值
    
    参数:
        数据: 数值数据
        
    返回:
        平均值
        
    示例:
        >>> 平均值([1, 2, 3, 4, 5])
        3.0
    """
    return statistics.mean(数据)


def 中位数(数据: Iterable[Union[int, float]]) -> Union[int, float]:
    """
    计算中位数
    
    参数:
        数据: 数值数据
        
    返回:
        中位数
        
    示例:
        >>> 中位数([1, 3, 5, 7, 9])
        5
        >>> 中位数([1, 2, 3, 4])
        2.5
    """
    return statistics.median(数据)


def 众数(数据: Iterable) -> any:
    """
    计算众数（出现最多的值）
    
    参数:
        数据: 数据
        
    返回:
        众数
        
    示例:
        >>> 众数([1, 2, 2, 3, 3, 3, 4])
        3
    """
    return statistics.mode(数据)


def 所有众数(数据: Iterable) -> List:
    """
    计算所有众数
    
    参数:
        数据: 数据
        
    返回:
        众数列表
        
    示例:
        >>> 所有众数([1, 1, 2, 2, 3])
        [1, 2]
    """
    return statistics.multimode(数据)


def 几何平均值(数据: Iterable[Union[int, float]]) -> float:
    """
    计算几何平均值
    
    参数:
        数据: 正数数据
        
    返回:
        几何平均值
        
    示例:
        >>> 几何平均值([1, 2, 4])
        2.0
    """
    return statistics.geometric_mean(数据)


def 调和平均值(数据: Iterable[Union[int, float]]) -> float:
    """
    计算调和平均值
    
    参数:
        数据: 非零数值数据
        
    返回:
        调和平均值
        
    示例:
        >>> 调和平均值([1, 2, 4])
        1.7142857142857142
    """
    return statistics.harmonic_mean(数据)


# ============================================================================
# 离散程度度量
# ============================================================================

def 方差(
    数据: Iterable[Union[int, float]],
    总体方差: bool = False
) -> float:
    """
    计算方差
    
    参数:
        数据: 数值数据
        总体方差: 是否计算总体方差（False为样本方差）
        
    返回:
        方差
        
    示例:
        >>> 方差([1, 2, 3, 4, 5])
        2.5
        >>> 方差([1, 2, 3, 4, 5], 总体方差=True)
        2.0
    """
    if 总体方差:
        return statistics.pvariance(数据)
    return statistics.variance(数据)


def 标准差(
    数据: Iterable[Union[int, float]],
    总体标准差: bool = False
) -> float:
    """
    计算标准差
    
    参数:
        数据: 数值数据
        总体标准差: 是否计算总体标准差（False为样本标准差）
        
    返回:
        标准差
        
    示例:
        >>> 标准差([1, 2, 3, 4, 5])
        1.5811388300841898
        >>> 标准差([1, 2, 3, 4, 5], 总体标准差=True)
        1.4142135623730951
    """
    if 总体标准差:
        return statistics.pstdev(数据)
    return statistics.stdev(数据)


def 极差(数据: Iterable[Union[int, float]]) -> Union[int, float]:
    """
    计算极差（最大值-最小值）
    
    参数:
        数据: 数值数据
        
    返回:
        极差
        
    示例:
        >>> 极差([1, 2, 3, 4, 5])
        4
    """
    数据列表 = list(数据)
    return max(数据列表) - min(数据列表)


def 四分位数(数据: Iterable[Union[int, float]], 分位数: float = 0.5) -> Union[int, float]:
    """
    计算分位数
    
    参数:
        数据: 数值数据
        分位数: 分位数值（0-1之间）
        
    返回:
        分位数值
        
    示例:
        >>> 四分位数([1, 2, 3, 4, 5], 0.25)
        1.75
        >>> 四分位数([1, 2, 3, 4, 5], 0.75)
        4.25
    """
    return statistics.quantiles(数据, n=int(1/分位数))[0] if 分位数 != 0.5 else 中位数(数据)


def 四分位距(数据: Iterable[Union[int, float]]) -> Union[int, float]:
    """
    计算四分位距（IQR）
    
    参数:
        数据: 数值数据
        
    返回:
        四分位距
        
    示例:
        >>> 四分位距([1, 2, 3, 4, 5, 6, 7, 8, 9])
        4.0
    """
    分位数列表 = statistics.quantiles(数据, n=4)
    return 分位数列表[2] - 分位数列表[0]


