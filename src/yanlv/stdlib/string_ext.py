# ============================================================================
# 字符串模板
# ============================================================================

class 字符串模板(string.Template):
    """
    字符串模板类，支持变量替换
    
    参数:
        模板字符串: 包含变量的模板字符串
        
    示例:
        >>> 模板 = 字符串模板('你好，$name！')
        >>> 模板.替换(name='张三')
        '你好，张三！'
    """
    
    def 替换(self, **关键字参数) -> str:
        """
        替换模板中的变量
        
        参数:
            **关键字参数: 变量名和值
            
        返回:
            替换后的字符串
        """
        return self.substitute(**关键字参数)
    
    def 安全替换(self, **关键字参数) -> str:
        """
        安全替换模板中的变量（未提供的变量保持原样）
        
        参数:
            **关键字参数: 变量名和值
            
        返回:
            替换后的字符串
        """
        return self.safe_substitute(**关键字参数)


def 创建模板(模板字符串: str) -> 字符串模板:
    """
    创建字符串模板
    
    参数:
        模板字符串: 包含变量的模板字符串
        
    返回:
        字符串模板对象
        
    示例:
        >>> 模板 = 创建模板('你好，$name！欢迎来到$place。')
        >>> 模板.替换(name='张三', place='北京')
        '你好，张三！欢迎来到北京。'
    """
    return 字符串模板(模板字符串)


# ============================================================================
# 字符串格式化工具
# ============================================================================

def 格式化字符串(
    模板: str,
    **变量
) -> str:
    """
    使用命名变量格式化字符串
    
    参数:
        模板: 格式化模板字符串
        **变量: 变量名和值
        
    返回:
        格式化后的字符串
        
    示例:
        >>> 格式化字符串('你好，{name}！', name='张三')
        '你好，张三！'
    """
    return 模板.format(**变量)


def 对齐字符串(
    字符串: str,
    宽度: int,
    对齐方式: str = '左',
    填充字符: str = ' '
) -> str:
    """
    对齐字符串
    
    参数:
        字符串: 要对齐的字符串
        宽度: 总宽度
        对齐方式: '左', '右', '中'
        填充字符: 填充字符
        
    返回:
        对齐后的字符串
        
    示例:
        >>> 对齐字符串('hello', 10, '中', '-')
        '--hello---'
    """
    if 对齐方式 == '左':
        return 字符串.ljust(宽度, 填充字符)
    elif 对齐方式 == '右':
        return 字符串.rjust(宽度, 填充字符)
    elif 对齐方式 == '中':
        return 字符串.center(宽度, 填充字符)
    else:
        raise ValueError("对齐方式必须是'左', '右'或'中'")


def 填充数字(
    数字: Union[int, str],
    宽度: int,
    填充字符: str = '0'
) -> str:
    """
    用指定字符填充数字到指定宽度
    
    参数:
        数字: 数字或数字字符串
        宽度: 总宽度
        填充字符: 填充字符
        
    返回:
        填充后的字符串
        
    示例:
        >>> 填充数字(42, 5)
        '00042'
        >>> 填充数字(42, 5, '-')
        '---42'
    """
    return str(数字).zfill(宽度) if 填充字符 == '0' else str(数字).rjust(宽度, 填充字符)


