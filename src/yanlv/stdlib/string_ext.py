# 字符串检查工具
# ============================================================================

def 是否数字字符串(字符串: str) -> bool:
    """
    检查字符串是否只包含数字
    
    参数:
        字符串: 要检查的字符串
        
    返回:
        是否只包含数字
        
    示例:
        >>> 是否数字字符串('12345')
        True
        >>> 是否数字字符串('123.45')
        False
    """
    return 字符串.isdigit()


def 是否字母字符串(字符串: str) -> bool:
    """
    检查字符串是否只包含字母
    
    参数:
        字符串: 要检查的字符串
        
    返回:
        是否只包含字母
        
    示例:
        >>> 是否字母字符串('hello')
        True
        >>> 是否字母字符串('hello123')
        False
    """
    return 字符串.isalpha()


def 是否字母数字字符串(字符串: str) -> bool:
    """
    检查字符串是否只包含字母和数字
    
    参数:
        字符串: 要检查的字符串
        
    返回:
        是否只包含字母和数字
        
    示例:
        >>> 是否字母数字字符串('hello123')
        True
        >>> 是否字母数字字符串('hello 123')
        False
    """
    return 字符串.isalnum()


def 是否空白字符串(字符串: str) -> bool:
    """
    检查字符串是否只包含空白字符
    
    参数:
        字符串: 要检查的字符串
        
    返回:
        是否只包含空白字符
        
    示例:
        >>> 是否空白字符串('   ')
        True
        >>> 是否空白字符串('  a  ')
        False
    """
    return 字符串.isspace()


def 是否小写字符串(字符串: str) -> bool:
    """检查字符串是否全为小写"""
    return 字符串.islower()


def 是否大写字符串(字符串: str) -> bool:
    """检查字符串是否全为大写"""
    return 字符串.isupper()


def 是否标题格式(字符串: str) -> bool:
    """检查字符串是否为标题格式（每个单词首字母大写）"""
    return 字符串.istitle()


# ============================================================================
# 字符串转换工具
# ============================================================================

def 转为小写(字符串: str) -> str:
    """转换为小写"""
    return 字符串.lower()


def 转为大写(字符串: str) -> str:
    """转换为大写"""
    return 字符串.upper()


def 转为标题格式(字符串: str) -> str:
    """转换为标题格式（每个单词首字母大写）"""
    return 字符串.title()


def 转为首字母大写(字符串: str) -> str:
    """转换为首字母大写"""
    return 字符串.capitalize()


def 大小写互换(字符串: str) -> str:
    """互换大小写"""
    return 字符串.swapcase()


# ============================================================================
# 字符串清理工具
# ============================================================================

def 去除两端空白(字符串: str) -> str:
    """去除字符串两端的空白字符"""
    return 字符串.strip()


def 去除左端空白(字符串: str) -> str:
    """去除字符串左端的空白字符"""
    return 字符串.lstrip()


def 去除右端空白(字符串: str) -> str:
    """去除字符串右端的空白字符"""
    return 字符串.rstrip()


def 去除指定字符(字符串: str, 字符: str) -> str:
    """
    去除字符串两端指定的字符
    
    参数:
        字符串: 要处理的字符串
        字符: 要去除的字符
        
    返回:
        处理后的字符串
        
    示例:
        >>> 去除指定字符('###hello###', '#')
        'hello'
    """
    return 字符串.strip(字符)


