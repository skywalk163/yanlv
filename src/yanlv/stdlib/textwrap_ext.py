"""
言律语言textwrap模块扩展
提供textwrap标准库的中文版本
"""

import textwrap
from typing import Optional, List


def 填充文本(
    文本: str,
    宽度: int = 70,
    初始缩进: str = '',
    后续缩进: str = '',
    展开制表符: bool = True,
    替换空白字符: bool = True,
    丢弃空行: bool = True
) -> str:
    """
    填充文本到指定宽度
    
    参数:
        文本: 要填充的文本
        宽度: 每行最大宽度
        初始缩进: 第一行的缩进
        后续缩进: 后续行的缩进
        展开制表符: 是否展开制表符
        替换空白字符: 是否替换空白字符
        丢弃空行: 是否丢弃空行
        
    返回:
        填充后的文本
        
    示例:
        >>> 填充文本('这是一个很长的文本需要被填充到指定宽度', 宽度=20)
        '这是一个很长的文本需要被填充到指定宽度'
    """
    return textwrap.fill(
        文本,
        width=宽度,
        initial_indent=初始缩进,
        subsequent_indent=后续缩进,
        expand_tabs=展开制表符,
        replace_whitespace=替换空白字符,
        drop_whitespace=丢弃空行
    )


def 包装文本(
    文本: str,
    宽度: int = 70,
    初始缩进: str = '',
    后续缩进: str = '',
    展开制表符: bool = True,
    替换空白字符: bool = True,
    丢弃空行: bool = True
) -> List[str]:
    """
    包装文本为多行列表
    
    参数:
        文本: 要包装的文本
        宽度: 每行最大宽度
        初始缩进: 第一行的缩进
        后续缩进: 后续行的缩进
        展开制表符: 是否展开制表符
        替换空白字符: 是否替换空白字符
        丢弃空行: 是否丢弃空行
        
    返回:
        文本行列表
        
    示例:
        >>> 包装文本('这是一个很长的文本', 宽度=10)
        ['这是一个很长的', '文本']
    """
    return textwrap.wrap(
        文本,
        width=宽度,
        initial_indent=初始缩进,
        subsequent_indent=后续缩进,
        expand_tabs=展开制表符,
        replace_whitespace=替换空白字符,
        drop_whitespace=丢弃空行
    )


def 缩进文本(
    文本: str,
    前缀: str,
    谓词: Optional[callable] = None
) -> str:
    """
    为文本添加缩进
    
    参数:
        文本: 要缩进的文本
        前缀: 缩进前缀
        谓词: 判断是否缩进的函数（None表示所有行都缩进）
        
    返回:
        缩进后的文本
        
    示例:
        >>> 缩进文本('hello\\nworld', '  ')
        '  hello\\n  world'
    """
    return textwrap.indent(文本, 前缀, 谓词)


def 缩进所有行(文本: str, 缩进字符串: str = '    ') -> str:
    """
    缩进所有行
    
    参数:
        文本: 要缩进的文本
        缩进字符串: 缩进字符串
        
    返回:
        缩进后的文本
        
    示例:
        >>> 缩进所有行('hello\\nworld', '  ')
        '  hello\\n  world'
    """
    return 缩进文本(文本, 缩进字符串)


def 去除缩进(文本: str) -> str:
    """
    去除文本的公共缩进
    
    参数:
        文本: 要处理的文本
        
    返回:
        去除缩进后的文本
        
    示例:
        >>> 去除缩进('    hello\\n    world')
        'hello\\nworld'
    """
    return textwrap.dedent(文本)


def 缩短文本(
    文本: str,
    宽度: int,
    占位符: str = '...'
) -> str:
    """
    缩短文本到指定宽度
    
    参数:
        文本: 要缩短的文本
        宽度: 最大宽度
        占位符: 缩短时使用的占位符
        
    返回:
        缩短后的文本
        
    示例:
        >>> 缩短文本('这是一个很长的文本', 10)
        '这是一个...'
    """
    if len(文本) <= 宽度:
        return 文本
    
    可用宽度 = 宽度 - len(占位符)
    if 可用宽度 <= 0:
        return 占位符[:宽度]
    
    return 文本[:可用宽度] + 占位符


def 居中文本(
    文本: str,
    宽度: int,
    填充字符: str = ' '
) -> str:
    """
    居中文本
    
    参数:
        文本: 要居中的文本
        宽度: 总宽度
        填充字符: 填充字符
        
    返回:
        居中后的文本
        
    示例:
        >>> 居中文本('hello', 10)
        '  hello   '
    """
    return 文本.center(宽度, 填充字符)


def 左对齐文本(
    文本: str,
    宽度: int,
    填充字符: str = ' '
) -> str:
    """
    左对齐文本
    
    参数:
        文本: 要对齐的文本
        宽度: 总宽度
        填充字符: 填充字符
        
    返回:
        左对齐后的文本
        
    示例:
        >>> 左对齐文本('hello', 10)
        'hello     '
    """
    return 文本.ljust(宽度, 填充字符)


def 右对齐文本(
    文本: str,
    宽度: int,
    填充字符: str = ' '
) -> str:
    """
    右对齐文本
    
    参数:
        文本: 要对齐的文本
        宽度: 总宽度
        填充字符: 填充字符
        
    返回:
        右对齐后的文本
        
    示例:
        >>> 右对齐文本('hello', 10)
        '     hello'
    """
    return 文本.rjust(宽度, 填充字符)


def 格式化段落(
    文本: str,
    宽度: int = 70,
    首行缩进: int = 0,
    段落缩进: int = 0,
    行间距: int = 1
) -> str:
    """
    格式化段落
    
    参数:
        文本: 要格式化的文本
        宽度: 每行宽度
        首行缩进: 首行缩进空格数
        段落缩进: 段落缩进空格数
        行间距: 行间距
        
    返回:
        格式化后的文本
        
    示例:
        >>> 格式化段落('这是一个段落。需要被格式化。', 宽度=20)
    """
    首行缩进字符串 = ' ' * 首行缩进
    后续缩进字符串 = ' ' * 段落缩进
    
    行列表 = 包装文本(
        文本,
        宽度=宽度,
        初始缩进=首行缩进字符串,
        后续缩进=后续缩进字符串
    )
    
    分隔符 = '\n' * 行间距
    return 分隔符.join(行列表)


def 对齐多行文本(
    文本列表: List[str],
    对齐方式: str = '左',
    宽度: Optional[int] = None
) -> List[str]:
    """
    对齐多行文本
    
    参数:
        文本列表: 文本列表
        对齐方式: '左', '右', '中'
        宽度: 宽度（None表示自动计算）
        
    返回:
        对齐后的文本列表
        
    示例:
        >>> 对齐多行文本(['a', 'bb', 'ccc'], 对齐方式='右')
        ['  a', ' bb', 'ccc']
    """
    if 宽度 is None:
        宽度 = max(len(文本) for 文本 in 文本列表)
    
    对齐函数 = {
        '左': 左对齐文本,
        '右': 右对齐文本,
        '中': 居中文本
    }
    
    return [对齐函数[对齐方式](文本, 宽度) for 文本 in 文本列表]


def 添加行号(
    文本: str,
    起始行号: int = 1,
    行号宽度: int = 4,
    分隔符: str = ' | '
) -> str:
    """
    为文本添加行号
    
    参数:
        文本: 要添加行号的文本
        起始行号: 起始行号
        行号宽度: 行号宽度
        分隔符: 分隔符
        
    返回:
        添加行号后的文本
        
    示例:
        >>> 添加行号('hello\\nworld')
        '   1 | hello\\n   2 | world'
    """
    行列表 = 文本.split('\n')
    结果行列表 = []
    
    for i, 行 in enumerate(行列表, 起始行号):
        行号字符串 = 右对齐文本(str(i), 行号宽度)
        结果行列表.append(f'{行号字符串}{分隔符}{行}')
    
    return '\n'.join(结果行列表)


def 创建文本包装器(
    宽度: int = 70,
    初始缩进: str = '',
    后续缩进: str = '',
    展开制表符: bool = True,
    替换空白字符: bool = True,
    丢弃空行: bool = True
) -> textwrap.TextWrapper:
    """
    创建文本包装器对象
    
    参数:
        宽度: 每行宽度
        初始缩进: 第一行缩进
        后续缩进: 后续行缩进
        展开制表符: 是否展开制表符
        替换空白字符: 是否替换空白字符
        丢弃空行: 是否丢弃空行
        
    返回:
        TextWrapper对象
        
    示例:
        >>> 包装器 = 创建文本包装器(宽度=20)
        >>> 包装器.fill('这是一个很长的文本')
    """
    包装器 = textwrap.TextWrapper(
        width=宽度,
        initial_indent=初始缩进,
        subsequent_indent=后续缩进,
        expand_tabs=展开制表符,
        replace_whitespace=替换空白字符,
        drop_whitespace=丢弃空行
    )
    return 包装器


