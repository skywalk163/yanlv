class 泛型基类(Generic):
    """
    泛型基类
    
    示例:
        >>> T = TypeVar('T')
        >>> class 容器(泛型基类[T]):
        ...     def __init__(self, 值: T):
        ...         self.值 = 值
    """
    pass


def 创建泛型类(名称: str, *类型变量) -> type:
    """
    创建泛型类
    
    参数:
        名称: 类名称
        *类型变量: 类型变量
        
    返回:
        泛型类
        
    示例:
        >>> T = TypeVar('T')
        >>> 容器类 = 创建泛型类('容器', T)
    """
    if 类型变量:
        return type(名称, (Generic[类型变量],), {})
    return type(名称, (Generic,), {})


