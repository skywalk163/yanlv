def 类变量(类型) -> ClassVar:
    """
    标记为类变量
    
    参数:
        类型: 变量类型
        
    返回:
        ClassVar类型提示
        
    示例:
        >>> class MyClass:
        ...     计数: 类变量(int) = 0
    """
    return ClassVar[类型]


def 最终类型(类型) -> Final:
    """
    标记为最终类型（不可重写）
    
    参数:
        类型: 变量类型
        
    返回:
        Final类型提示
        
    示例:
        >>> class MyClass:
        ...     常量: 最终类型(int) = 100
    """
    return Final[类型]


def 字面值(*值) -> Literal:
    """
    创建字面值类型
    
    参数:
        *值: 允许的字面值
        
    返回:
        Literal类型提示
        
    示例:
        >>> def 函数(状态: 字面值('成功', '失败')):
        ...     pass
    """
    return Literal[值]


