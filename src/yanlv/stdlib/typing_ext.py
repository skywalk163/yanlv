def 创建类型变量(名称: str, *约束) -> TypeVar:
    """
    创建类型变量
    
    参数:
        名称: 类型变量名称
        *约束: 类型约束
        
    返回:
        TypeVar对象
        
    示例:
        >>> T = 创建类型变量('T')
        >>> U = 创建类型变量('U', int, float)
    """
    return TypeVar(名称, *约束)


