def 转为可选类型(类型) -> Optional:
    """
    将类型转换为Optional类型
    
    参数:
        类型: 原始类型
        
    返回:
        Optional类型
        
    示例:
        >>> 转为可选类型(int)
        Optional[int]
    """
    return Optional[类型]


def 转为列表类型提示(元素类型) -> List:
    """
    创建List类型提示
    
    参数:
        元素类型: 列表元素类型
        
    返回:
        List类型提示
        
    示例:
        >>> 转为列表类型提示(int)
        List[int]
    """
    return List[元素类型]


def 转为字典类型提示(键类型, 值类型) -> Dict:
    """
    创建Dict类型提示
    
    参数:
        键类型: 字典键类型
        值类型: 字典值类型
        
    返回:
        Dict类型提示
        
    示例:
        >>> 转为字典类型提示(str, int)
        Dict[str, int]
    """
    return Dict[键类型, 值类型]


def 转为联合类型(*类型) -> Union:
    """
    创建Union类型提示
    
    参数:
        *类型: 联合的类型
        
    返回:
        Union类型提示
        
    示例:
        >>> 转为联合类型(int, str, float)
        Union[int, str, float]
    """
    return Union[类型]


