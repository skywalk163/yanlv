def 获取联合类型参数(类型提示) -> tuple:
    """
    获取Union类型的参数
    
    参数:
        类型提示: Union类型提示对象
        
    返回:
        类型参数元组
        
    示例:
        >>> 获取联合类型参数(Union[int, str])
        (int, str)
    """
    return getattr(类型提示, '__args__', ())


